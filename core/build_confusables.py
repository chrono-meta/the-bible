#!/usr/bin/env python3
"""Regenerate core/confusables_data.py from Unicode's UTS #39 confusables.txt (R11, DESIGN.md §4 R11).

usage: python3 core/build_confusables.py <path/to/confusables.txt>
       (download: https://www.unicode.org/Public/security/latest/confusables.txt)

Keeps only single-code-point sources whose prototype is a single ASCII letter — the class that spoofs
a Latin safety token one glyph at a time. Multi-code-point sources/targets (e.g. 'rn' -> 'm') are not
kept; that is a named residual in DESIGN.md §5. The output is data only (one dict), so normalization
stays stdlib-only and import-clean.
"""
import os
import re
import sys


def main(path):
    header = open(path, encoding="utf-8-sig").read(2000)
    ver = (re.search(r"# Version: ([\d.]+)", header) or [None, "?"])[1]
    date = (re.search(r"# Date: ([^\n]+)", header) or [None, "?"])[1].strip()
    m = {}
    for line in open(path, encoding="utf-8-sig"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        src, tgt, *_ = [x.strip() for x in line.split(";")]
        s = "".join(chr(int(h, 16)) for h in src.split())
        t = "".join(chr(int(h, 16)) for h in tgt.split())
        if len(s) == 1 and len(t) == 1 and t.isascii() and t.isalpha():
            m[s] = t.lower()
    out = os.path.join(os.path.dirname(__file__), "confusables_data.py")
    with open(out, "w", encoding="utf-8") as f:
        f.write('"""GENERATED by core/build_confusables.py — do not edit by hand.\n\n')
        f.write(f"Source: Unicode UTS #39 confusables.txt, version {ver} ({date}).\n")
        f.write("© Unicode, Inc. Used under the Unicode License v3 (https://www.unicode.org/license.txt).\n")
        f.write("Single-code-point source -> lowercase ASCII-letter prototype. DETECTION-ONLY data for\n")
        f.write('normalization.skeleton_full(); never applied to canonical text.\n"""\n')
        f.write(f"VERSION = {ver!r}\n")
        f.write("CONFUSABLE_TO_LATIN = {\n")
        for k in sorted(m):
            f.write(f"    {ascii(k)}: {m[k]!r},\n")
        f.write("}\n")
    print(f"wrote {out}: {len(m)} entries (confusables.txt {ver})")


if __name__ == "__main__":
    main(sys.argv[1])
