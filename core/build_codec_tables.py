#!/usr/bin/env python3
"""Regenerate core/codec_tables.py — the Ecoji and Base2048 alphabets (R11b, DESIGN.md §4 R11).

usage (in a throwaway venv, NOT a dependency of this repo):
    python3 -m venv /tmp/v && /tmp/v/bin/pip install ecoji==0.1.1 base2048==0.1.3
    /tmp/v/bin/python core/build_codec_tables.py

Ecoji: the table is read straight from the package's mapping module.
Base2048: the package is a compiled extension, so the table is PROBED from its encoder — table[v] is the
first character of encode(v << 5 as 2 bytes); the 8 tail characters are collected from inputs whose
final bit-chunk is 1-3 bits (their value is right-aligned). The probe then round-trips 3,000 random
byte strings through normalization's own decoder logic and refuses to write on any mismatch.
"""
import os
import random


def main():
    import base2048
    import ecoji
    from ecoji import mapping as em

    full = {}
    for v in range(2048):
        full[v] = base2048.encode((v << 5).to_bytes(2, "big"))[0]
    assert len(set(full.values())) == 2048
    tail = {}
    for n in (3, 7, 10, 14, 18, 21):
        r = (8 * n) % 11
        for t in range(1 << r):
            ch = base2048.encode(t.to_bytes(n, "big"))[-1]
            assert tail.setdefault(ch, t) == t
    assert len(tail) == 8 and not (set(tail) & set(full.values()))

    out = os.path.join(os.path.dirname(__file__), "codec_tables.py")
    with open(out, "w", encoding="utf-8") as f:
        f.write('"""GENERATED by core/build_codec_tables.py — do not edit by hand. DETECTION-ONLY data.\n\n')
        f.write(f"Ecoji alphabet: ecoji {__import__('importlib.metadata').metadata.version('ecoji')} (Apache-2.0, github.com/keith-turner/ecoji).\n")
        f.write("Base2048 alphabet: probed from the `base2048` 0.1.3 package (MIT; alphabet by qntm,\n")
        f.write('github.com/qntm/base2048, MIT).\n"""\n')
        f.write(f"ECOJI = {ascii(''.join(em.EMOJIS))}\n")
        f.write(f"ECOJI_PAD = {ascii(em.PADDING)}\n")
        f.write(f"ECOJI_PAD4 = {ascii(em.PADDING40 + em.PADDING41 + em.PADDING42 + em.PADDING43)}\n")
        f.write(f"B2048 = {ascii(''.join(full[v] for v in range(2048)))}\n")
        f.write(f"B2048_TAIL = {ascii(''.join(c for c, _ in sorted(tail.items(), key=lambda kv: kv[1])))}\n")
    print(f"wrote {out}")

    # verify with the repo's OWN decoders (fresh import of the file just written)
    import importlib
    import sys
    sys.path.insert(0, os.path.dirname(__file__))
    import codec_tables
    importlib.reload(codec_tables)
    import normalization as n
    importlib.reload(n)
    rng = random.Random(1)
    import io
    for _ in range(3000):
        x = bytes(rng.randrange(256) for _ in range(rng.randrange(1, 64)))
        assert n._b2048_bytes(base2048.encode(x)) == x, x
        w = io.StringIO()
        ecoji.encode(io.BytesIO(x), w)
        assert n._ecoji_bytes(w.getvalue()) == x, x
    print("round-trip OK (3,000 random inputs per codec)")


if __name__ == "__main__":
    main()
